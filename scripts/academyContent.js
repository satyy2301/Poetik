function assertAcademyContent() {
  if (LESSONS.length !== 40) {
    throw new Error(`Expected 40 lessons, found ${LESSONS.length}`);
  }
  if (CHALLENGES.length !== 90) {
    throw new Error(`Expected 90 challenges, found ${CHALLENGES.length}`);
  }
  if (new Set(CHALLENGES).size !== 90) {
    throw new Error('Challenge prompts are not all distinct');
  }

  const titles = new Set();
  LESSONS.forEach((lesson, index) => {
    if (titles.has(lesson.title)) throw new Error(`Duplicate title: ${lesson.title}`);
    titles.add(lesson.title);
    if (lesson.lesson_order !== index + 1) {
      throw new Error(`Order gap at ${lesson.title}`);
    }
    if (lesson.type !== TRACK_RUN[index]) {
      throw new Error(`${lesson.title} is ${lesson.type}, expected ${TRACK_RUN[index]}`);
    }
    const stepTypes = lesson.steps.map((step) => step.type).join(',');
    if (stepTypes !== 'theory,example,quiz,exercise') {
      throw new Error(`${lesson.title} steps are ${stepTypes}`);
    }
    const example = lesson.steps[1];
    if (!example.examples || !example.examples.length) {
      throw new Error(`${lesson.title} has no example lines`);
    }
    const check = lesson.steps[2];
    if (!check.options || check.answerIndex == null || !check.options[check.answerIndex]) {
      throw new Error(`${lesson.title} check question is incomplete`);
    }
    if (lesson.quiz.length !== 6) throw new Error(`${lesson.title} needs 6 quiz questions`);
    lesson.quiz.forEach((question) => {
      if (question.options.length !== 4 || question.options[question.answerIndex] == null) {
        throw new Error(`Bad quiz item in ${lesson.title}`);
      }
    });
  });

  PRESERVED_TITLES.forEach((title) => {
    if (!titles.has(title)) throw new Error(`Missing preserved lesson: ${title}`);
  });
}

