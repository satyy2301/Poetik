function hashString(value) {
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function q(question, correct, wrongs) {
  if (!question || !correct) throw new Error('Incomplete question');
  if (!Array.isArray(wrongs) || wrongs.length !== 3) {
    throw new Error(`Need 3 wrong answers: ${question}`);
  }
  if (new Set([correct, ...wrongs]).size !== 4) {
    throw new Error(`Duplicate options: ${question}`);
  }
  const options = wrongs.slice();
  const answerIndex = hashString(question) % 4;
  options.splice(answerIndex, 0, correct);
  return { question, options, answerIndex };
}

function lesson(spec) {
  const check = q(spec.check[0], spec.check[1], spec.check[2]);
  return {
    title: spec.title,
    description: spec.description,
    type: spec.type,
    difficulty: spec.difficulty,
    lesson_order: spec.lesson_order,
    xp_reward: [0, 25, 35, 45, 60][spec.difficulty],
    steps: [
      { type: 'theory', title: 'Theory', content: spec.theory },
      { type: 'example', title: 'Example', content: spec.example, examples: spec.examples },
      {
        type: 'quiz',
        title: 'Check',
        question: check.question,
        options: check.options,
        answerIndex: check.answerIndex,
      },
      { type: 'exercise', title: 'Write', content: spec.exercise, requiresResponse: true },
    ],
    quiz: spec.quiz.map((row) => q(row[0], row[1], row[2])),
  };
}

