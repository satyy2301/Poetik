function localIndicPoems(language) {
  return POEMS.filter((poem) => poem.language === language).map((poem) => ({
    title: poem.title,
    author: poem.author,
    content: poem.content,
    language: poem.language,
    era: 'classical',
    form: poem.form,
    source: 'public-domain',
    source_url: `https://poetik.local/indic/${poem.language}/${encodeURIComponent(poem.title)}`,
    line_count: poem.content.split('\n').length,
    word_count: poem.content.split(/\s+/).filter(Boolean).length,
    themes: ['literature'],
    visibility: 'public',
  }));
}

module.exports = { localIndicPoems };
